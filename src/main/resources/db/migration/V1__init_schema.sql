-- =========================================
-- users
-- =========================================
CREATE TABLE users (
                       id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                       email            VARCHAR(255) NOT NULL,
                       nickname         VARCHAR(20)  NOT NULL,
                       password_hash    VARCHAR(255) NOT NULL,
                       weekly_budget    INTEGER,
                       terms_agreed_at  TIMESTAMPTZ  NOT NULL,
                       created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
                       CONSTRAINT uk_users_email UNIQUE (email)
);

-- =========================================
-- refresh_tokens
-- =========================================
CREATE TABLE refresh_tokens (
                                id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                                token_hash  VARCHAR(255) NOT NULL,
                                expires_at  TIMESTAMPTZ  NOT NULL,
                                created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
                                CONSTRAINT uk_refresh_tokens_token_hash UNIQUE (token_hash)
);
CREATE INDEX idx_refresh_tokens_user_id ON refresh_tokens (user_id);

-- =========================================
-- expenses
-- =========================================
CREATE TABLE expenses (
                          id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                          spent_on    DATE         NOT NULL,
                          item        VARCHAR(20)  NOT NULL,
                          amount      INTEGER      NOT NULL,
                          reason      VARCHAR(20)  NOT NULL,
                          regret      BOOLEAN      NOT NULL,
                          mood        VARCHAR(20),
                          memo        VARCHAR(100),
                          created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
                          CONSTRAINT ck_expenses_item
                              CHECK (item IN ('FOOD', 'DELIVERY', 'CAFE', 'SHOPPING', 'TRANSPORT', 'ETC')),
                          CONSTRAINT ck_expenses_reason
                              CHECK (reason IN ('NEED', 'STRESS', 'DISCOUNT', 'IMPULSE', 'REWARD', 'HABIT')),
                          CONSTRAINT ck_expenses_mood
                              CHECK (mood IN ('GOOD', 'NORMAL', 'TIRED', 'DEPRESSED'))
);
CREATE INDEX idx_expenses_user_id_spent_on ON expenses (user_id, spent_on);

-- =========================================
-- insights
-- =========================================
CREATE TABLE insights (
                          id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          user_id       BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                          period_type   VARCHAR(10)  NOT NULL,
                          period_start  DATE         NOT NULL,
                          result        JSONB        NOT NULL,
                          created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
                          CONSTRAINT ck_insights_period_type CHECK (period_type IN ('WEEK', 'MONTH'))
);
CREATE UNIQUE INDEX idx_insights_user_id_period ON insights (user_id, period_type, period_start);

-- =========================================
-- mission_recommendations
-- =========================================
CREATE TABLE mission_recommendations (
                                         id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                         user_id     BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                                         items       JSONB        NOT NULL,
                                         base_level  VARCHAR(10)  NOT NULL,
                                         selected    BOOLEAN      NOT NULL DEFAULT FALSE,
                                         created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
                                         CONSTRAINT ck_mission_recommendations_base_level
                                             CHECK (base_level IN ('EASY', 'BASIC', 'ADVANCED'))
);
CREATE INDEX idx_mission_recommendations_user_id ON mission_recommendations (user_id);

-- =========================================
-- missions
-- =========================================
CREATE TABLE missions (
                          id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                          user_id            BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
                          recommendation_id  BIGINT       REFERENCES mission_recommendations (id) ON DELETE SET NULL,
                          pattern_group      VARCHAR(20)  NOT NULL,
                          level              VARCHAR(10)  NOT NULL,
                          text               VARCHAR(100) NOT NULL,
                          started_on         DATE         NOT NULL,
                          done_days          SMALLINT     NOT NULL DEFAULT 0,
                          last_checked_on    DATE,
                          result             VARCHAR(10),
                          difficulty         VARCHAR(20),
                          memo               VARCHAR(100),
                          judged_at          TIMESTAMPTZ,
                          created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
                          CONSTRAINT ck_missions_pattern_group
                              CHECK (pattern_group IN ('STRESS_DELIVERY', 'IMPULSE_SHOPPING', 'HABIT_CAFE_FOOD', 'DEFAULT')),
                          CONSTRAINT ck_missions_level
                              CHECK (level IN ('EASY', 'BASIC', 'ADVANCED')),
                          CONSTRAINT ck_missions_result
                              CHECK (result IN ('ACHIEVED', 'FAILED')),
                          CONSTRAINT ck_missions_difficulty
                              CHECK (difficulty IN ('NO_TIME', 'HABIT_UNCHANGED', 'FORGOT', 'OTHER')),
                          CONSTRAINT ck_missions_done_days
                              CHECK (done_days BETWEEN 0 AND 7)
);
CREATE INDEX idx_missions_user_id ON missions (user_id);

-- 사용자당 진행 중(result IS NULL) 미션은 1개만 허용
CREATE UNIQUE INDEX uk_missions_user_in_progress ON missions (user_id) WHERE result IS NULL;